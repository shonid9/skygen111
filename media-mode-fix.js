(()=>{
  'use strict';
  const IMAGE_RE=/\.(jpe?g|png|webp|tiff?)$/i;
  let selectedFile=null,lastScan=null,lastUrl=null;
  const $=s=>document.querySelector(s);
  const esc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  function rememberFile(f){if(f&&IMAGE_RE.test(f.name||'')){selectedFile=f;window.__EMET_MEDIA_FILE=f;}else if(f){selectedFile=null;window.__EMET_MEDIA_FILE=null;}}
  document.addEventListener('change',e=>{if(e.target?.id==='fileInput')rememberFile(e.target.files?.[0]);},true);
  document.addEventListener('drop',e=>{const f=e.dataTransfer?.files?.[0];if(f)rememberFile(f);},true);

  const nativeFetch=window.fetch.bind(window);
  window.fetch=async function(input,init){
    const r=await nativeFetch(input,init);
    try{
      const u=typeof input==='string'?input:input?.url||'';
      if(u.includes('/api/analyze')&&!u.includes('/api/analyze-text')&&r.ok){
        const d=await r.clone().json();
        lastScan=d;window.__EMET_LAST_SCAN=d;
        setTimeout(()=>refresh(d),30);
        setTimeout(()=>refresh(d),250);
      }
    }catch{}
    return r;
  };

  function estimateImage(m){
    const s=Number(m?.syntheticImageSignal?.score||0), ela=Number(m?.recompression?.recompressionAnomalyScore||0), copy=Number(m?.copyMove?.copyMoveSignal||0), p=m?.pixelForensics||{};
    const fp=(m?.metadata?.generatorFingerprints||[]).length;
    if(fp) return {score:Math.max(94,s),confidence:'high',label:'Strong AI origin signal',whole:true,reasons:[`Generator fingerprint: ${(m.metadata.generatorFingerprints||[]).join(', ')}`]};
    let score=Math.round(s*.5+ela*.18+copy*.14+Math.min(100,Math.max(0,(3-Number(p.noiseResidual||3))*18))*.1+Math.min(100,Number(p.edgeEnergy||0)*3)*.08);
    score=Math.max(1,Math.min(99,score));
    const confidence=score>=70?'medium-high':score>=45?'medium':'low-medium';
    const label=score>=75?'Strong AI or synthetic-edit signal':score>=55?'Elevated AI or synthetic-edit signal':score>=30?'Some synthetic characteristics':'Low synthetic signal';
    return {score,confidence,label,whole:score>=88,reasons:m?.syntheticImageSignal?.reasons||[]};
  }

  function pruneTextOnlyPanels(results){
    [...results.querySelectorAll('.reviewCard,.reviewLegacy,.verdictHero,.resultCard')].forEach(card=>{
      const txt=(card.textContent||'').toLowerCase();
      if(card.dataset?.mm==='1'||card.classList.contains('emetImageOriginPanel')) return;
      if(txt.includes('writing signals')||txt.includes('what the text looks like')||txt.includes('words read')||txt.includes('authorship source')||txt.includes('technical evidence detail')||txt.includes('ai origin map')||txt.includes('document map')) card.remove();
    });
  }

  function panelHtml(m,e){
    const fp=(m?.metadata?.generatorFingerprints||[]).join(', ');
    return `<section class="resultCard emetImageOriginPanel" data-image-origin-panel="1">
      <div class="emetImageHero"><div><div class="eyebrow">EMET IMAGE ORIGIN MAP</div><h2>${esc(e.score)}% AI origin estimate</h2><p>${esc(e.label)} · confidence ${esc(e.confidence)}.</p></div><div class="emetImagePct">${esc(e.score)}<small>%</small></div></div>
      <div class="emetImageStage"><canvas class="emetImageCanvas" aria-label="Image forensic attention map"></canvas><div class="emetLegend"><span><i class="whole"></i>whole-image origin signal</span><span><i class="local"></i>local forensic attention</span></div></div>
      <div class="emetImageSummary"><div><span>Generator fingerprint</span><b>${fp?esc(fp):'None found'}</b></div><div><span>Pixel / noise layer</span><b>${Math.round(Number(m?.syntheticImageSignal?.score||0))}/100</b></div><div><span>Recompression</span><b>${m?.recompression?.supported?Math.round(Number(m.recompression.recompressionAnomalyScore||0))+'/100':'N/A'}</b></div><div><span>Repeated-region screen</span><b>${Math.round(Number(m?.copyMove?.copyMoveSignal||0))}/100</b></div></div>
      <p class="emetImageNote">Yellow marks the regions EMET considers most relevant for synthetic generation or local editing review. When the evidence points to the whole image, the entire image is lightly marked. Region boundaries are forensic attention areas, not a claim that one exact pixel was certainly generated by AI.</p>
    </section>`;
  }

  async function drawMap(canvas,file,e){
    if(!canvas||!file)return;
    if(lastUrl)URL.revokeObjectURL(lastUrl);lastUrl=URL.createObjectURL(file);
    const img=new Image();img.decoding='async';img.src=lastUrl;await img.decode();
    const max=1000,scale=Math.min(1,max/Math.max(img.naturalWidth,img.naturalHeight)),w=Math.max(1,Math.round(img.naturalWidth*scale)),h=Math.max(1,Math.round(img.naturalHeight*scale));
    canvas.width=w;canvas.height=h;const ctx=canvas.getContext('2d',{willReadFrequently:true});ctx.drawImage(img,0,0,w,h);
    const original=ctx.getImageData(0,0,w,h),data=original.data;
    const cols=12,rows=Math.max(8,Math.round(12*h/w)),tw=w/cols,th=h/rows,tiles=[];
    for(let gy=0;gy<rows;gy++)for(let gx=0;gx<cols;gx++){
      const x0=Math.floor(gx*tw),x1=Math.min(w,Math.ceil((gx+1)*tw)),y0=Math.floor(gy*th),y1=Math.min(h,Math.ceil((gy+1)*th));
      let n=0,sum=0,sum2=0,res=0,edge=0;
      for(let y=y0+1;y<y1-1;y+=2)for(let x=x0+1;x<x1-1;x+=2){const i=(y*w+x)*4,l=.2126*data[i]+.7152*data[i+1]+.0722*data[i+2];const il=(y*w+x-1)*4,ir=(y*w+x+1)*4,iu=((y-1)*w+x)*4,id=((y+1)*w+x)*4;const ll=.2126*data[il]+.7152*data[il+1]+.0722*data[il+2],lr=.2126*data[ir]+.7152*data[ir+1]+.0722*data[ir+2],lu=.2126*data[iu]+.7152*data[iu+1]+.0722*data[iu+2],ld=.2126*data[id]+.7152*data[id+1]+.0722*data[id+2];const avg=(ll+lr+lu+ld)/4;sum+=l;sum2+=l*l;res+=Math.abs(l-avg);edge+=Math.abs(l-ll)+Math.abs(l-lu);n++;}
      const mean=sum/(n||1),sd=Math.sqrt(Math.max(0,sum2/(n||1)-mean*mean)),r=res/(n||1),ed=edge/(2*(n||1));tiles.push({gx,gy,x0,y0,x1,y1,raw:r*.62+ed*.28+sd*.10});
    }
    const vals=tiles.map(t=>t.raw).sort((a,b)=>a-b),median=vals[Math.floor(vals.length*.5)]||1,p85=vals[Math.floor(vals.length*.85)]||median;
    ctx.putImageData(original,0,0);
    if(e.whole){ctx.fillStyle='rgba(255,220,72,.18)';ctx.fillRect(0,0,w,h);ctx.strokeStyle='rgba(236,176,0,.85)';ctx.lineWidth=Math.max(2,w/350);ctx.strokeRect(2,2,w-4,h-4);}else{
      const hot=tiles.filter(t=>t.raw>=p85&&t.raw>median*1.08).sort((a,b)=>b.raw-a.raw).slice(0,Math.max(6,Math.round(tiles.length*.16)));
      hot.forEach((t,i)=>{const z=(t.raw-p85)/Math.max(1,p85),a=Math.min(.35,.14+z*.12);ctx.fillStyle=`rgba(255,218,70,${a})`;ctx.fillRect(t.x0,t.y0,t.x1-t.x0,t.y1-t.y0);ctx.strokeStyle='rgba(228,164,0,.72)';ctx.lineWidth=Math.max(1,w/700);ctx.strokeRect(t.x0+.5,t.y0+.5,t.x1-t.x0-1,t.y1-t.y0-1);});
    }
  }

  function refresh(d=lastScan){
    const results=$('#results'),m=d?.multimodal;if(!results||!m||m.kind!=='image')return;
    pruneTextOnlyPanels(results);
    results.querySelector('[data-image-origin-panel]')?.remove();
    const e=estimateImage(m),wrap=document.createElement('div');wrap.innerHTML=panelHtml(m,e);const panel=wrap.firstElementChild;results.prepend(panel);
    if(selectedFile)drawMap(panel.querySelector('canvas'),selectedFile,e).catch(()=>{});
  }

  const obs=new MutationObserver(()=>{if(lastScan?.multimodal?.kind==='image')setTimeout(()=>refresh(lastScan),0)});
  const start=()=>{const r=$('#results');if(r)obs.observe(r,{childList:true,subtree:false});};
  if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',start);else start();
})();